import {test,expect} from '@playwright/test';
import {navigateMainSection} from './navigation';

test('system monitor shows local capacity and inference queue without exposing request data',async({page})=>{
  let samples=0;
  const headers={'access-control-allow-origin':'http://127.0.0.1:5173','access-control-allow-headers':'authorization,content-type,last-event-id','access-control-allow-methods':'GET,POST,OPTIONS'};
  const firstAdapter={device_id:'dxgi:00000000:00000001',name:'NVIDIA GeForce RTX 5080',memory_total_bytes:16*1024**3,memory_free_bytes:6*1024**3,utilization_percent:24};
  const secondAdapter={device_id:'dxgi:00000000:00000002',name:'NVIDIA GeForce RTX 5080',memory_total_bytes:16*1024**3,memory_free_bytes:4*1024**3,utilization_percent:80};
  await page.route('http://127.0.0.1:8765/**',async route=>{
    const request=route.request();const path=new URL(request.url()).pathname;
    if(request.method()==='OPTIONS')return route.fulfill({status:204,headers});
    if(path==='/system/resources'){
      samples++;
      const currentFirst={...firstAdapter,memory_free_bytes:(samples===1?6:5)*1024**3,utilization_percent:samples===1?24:40};
      const currentSecond={...secondAdapter,memory_free_bytes:(samples===1?4:3)*1024**3,utilization_percent:samples===1?80:95};
      return route.fulfill({headers,json:{sampled_at:'2026-11-14T17:00:00Z',platform:'win32',logical_processors:16,cpu_percent:42.5,memory_total_bytes:32*1024**3,memory_available_bytes:8*1024**3,memory_used_percent:75,disk_total_bytes:2*1024**4,disk_free_bytes:512*1024**3,queue_active:true,queue_waiting:2,queue_reserved_weight:640,queue_max_reserved_weight:2_000_000,queue_max_pending:16,gpu_devices:[...(samples===1?[currentFirst,currentSecond]:[currentSecond,currentFirst]),{name:'AMD Radeon(TM) Graphics',memory_total_bytes:2*1024**3,memory_free_bytes:1536*1024**2,utilization_percent:0},{name:'Intel Arc Graphics',memory_total_bytes:8*1024**3,memory_free_bytes:7*1024**3,utilization_percent:null}],accelerator_telemetry_available:true}});
    }
    if(path==='/runs/latest-unfinished')return route.fulfill({headers,json:null});
    if(path==='/runs')return route.fulfill({headers,json:{items:[],next_cursor:null}});
    if(path==='/models')return route.fulfill({headers,json:[{id:'fixture/model'}]});
    if(path==='/providers')return route.fulfill({headers,json:[{id:'lm-studio',status:'connected'}]});
    if(path==='/execution/distributions')return route.fulfill({headers,json:{state:'unsupported',distributions:[]}});
    return route.fulfill({status:404,headers});
  });
  await page.goto('/');
  await page.getByLabel('Engine token').fill('x'.repeat(32));
  await page.getByRole('button',{name:'Connect',exact:true}).click();
  await navigateMainSection(page,'System monitor');
  await expect(page.getByRole('region',{name:'Processor'})).toContainText('42.5%');
  await expect(page.getByRole('region',{name:'Memory'})).toContainText('75.0% used');
  await expect(page.getByRole('region',{name:'Profile drive'})).toContainText('75.0% used');
  await expect(page.getByRole('region',{name:'Inference queue'})).toContainText('2 waiting');
  await expect(page.getByRole('region',{name:'Inference queue'})).toContainText('640 estimated queue weight');
  await expect(page.getByRole('region',{name:'Inference queue'})).toContainText('weight units');
  await expect(page.locator('.system-monitor-note')).toContainText('do not predict model tokenization or GPU memory requirements');
  const nvidiaAdapterOne=page.getByRole('region',{name:'NVIDIA GeForce RTX 5080 · Adapter 1'});
  const nvidiaAdapterTwo=page.getByRole('region',{name:'NVIDIA GeForce RTX 5080 · Adapter 2'});
  await expect(nvidiaAdapterOne).toContainText('24% active');
  await expect(nvidiaAdapterOne).toContainText('GPU memory free');
  await expect(nvidiaAdapterTwo).toContainText('80% active');
  await expect(nvidiaAdapterTwo).toContainText('GPU memory free');
  await expect(page.getByRole('region',{name:'AMD Radeon(TM) Graphics'})).toContainText('0% active');
  await expect(page.getByRole('region',{name:'AMD Radeon(TM) Graphics'})).toContainText('GPU memory free');
  await expect(page.getByRole('region',{name:'Intel Arc Graphics'})).toContainText('Unavailable');
  await expect(page.getByRole('region',{name:'Intel Arc Graphics'})).toContainText('GPU memory free');
  await expect(page.getByText(/GPU readings are reported when Windows adapter or NVIDIA driver telemetry is available/)).toBeVisible();
  await expect(page.locator('.system-monitor-updated')).toHaveCount(0);
  await page.getByRole('button',{name:'Refresh now'}).click();
  await expect(page.locator('.system-monitor-updated')).toContainText('System monitor updated');
  await expect(nvidiaAdapterOne).toContainText('40% active');
  await expect(nvidiaAdapterTwo).toContainText('95% active');
  const adapterOneTrace=await nvidiaAdapterOne.locator('polyline').getAttribute('points');
  const adapterTwoTrace=await nvidiaAdapterTwo.locator('polyline').getAttribute('points');
  expect(adapterOneTrace).not.toBe(adapterTwoTrace);
  await expect(page.getByRole('img',{name:'Processor trend across 2 recent local samples'})).toBeVisible();
  await expect(page.getByRole('img',{name:'Memory trend across 2 recent local samples'})).toBeVisible();
  await expect(page.getByRole('img',{name:'Profile drive trend across 2 recent local samples'})).toBeVisible();
  await expect(page.getByRole('img',{name:'NVIDIA GeForce RTX 5080 · Adapter 1 trend across 2 recent local samples'})).toBeVisible();
  await expect(page.getByRole('img',{name:'NVIDIA GeForce RTX 5080 · Adapter 2 trend across 2 recent local samples'})).toBeVisible();
  await expect(page.getByRole('img',{name:'AMD Radeon(TM) Graphics trend across 2 recent local samples'})).toBeVisible();
  await expect(page.getByRole('img',{name:'Intel Arc Graphics trend across 2 recent local samples'})).toHaveCount(0);
  expect(samples).toBe(2);
});
